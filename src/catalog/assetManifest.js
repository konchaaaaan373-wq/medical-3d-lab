/**
 * Asset manifest — where every external 3D asset came from and what was done to it.
 *
 * A GLB on disk carries none of this. Once a mesh has been downloaded,
 * segmented, cleaned in Blender and exported, nothing in the file says which
 * atlas release it began as, under what licence, whether a subject's imaging
 * is behind it, what units it is in, or which of its parts a scene may point at
 * by name. That information is lost at the moment of conversion unless it is
 * written down, so it is written down here, per asset, and tested.
 *
 * Two questions are deliberately kept apart:
 *
 * 1. **Is the record complete for its source type?** — `validateAssetManifest`.
 *    An imaging-derived asset must say how it was de-identified; a procedural
 *    one must say how to regenerate it; neither has to fill in the other's
 *    fields with a made-up "N/A".
 * 2. **May this asset ship to the public product?** — `assetReleaseProblems`.
 *    A licence recorded as `unknown` is a valid record of an investigation in
 *    progress. It is not a licence gate passed.
 *
 * The pipeline that produces an asset — source choice, licence and PHI review,
 * hashing, Slicer/Blender, export, validation, semantic and anatomy QA, device
 * QA, medical review, release — is `docs/asset-pipeline.md`. This file records
 * its outcome. Blender is an offline tool in that pipeline and never a runtime
 * dependency; MCP tooling is an operator's window onto it and never the record.
 *
 * Pure data and pure functions. No `three`, no DOM, no filesystem — a reader
 * for hashing is injected by whoever checks the files (`tests/asset-manifest.test.js`).
 */

export const ASSET_MANIFEST_SCHEMA_VERSION = 1;

/** Where an asset's geometry ultimately came from. Decides which conditional block is required. */
export const ASSET_SOURCE_TYPE = Object.freeze({
  /** A curated normal reference mesh or atlas release (HRA, Z-Anatomy, BodyParts3D, NIH 3D entries). */
  REFERENCE_ATLAS: 'reference-atlas',
  /** Segmented from CT/MRI or another imaging dataset. */
  IMAGING_DERIVED: 'imaging-derived',
  /** Generated by a script or generator from parameters, and reproducible from them. */
  PROCEDURAL: 'procedural',
  /** From a structural database accession (PDB and the like). */
  MOLECULAR: 'molecular',
  /** A texture, material or decoder someone else made, recorded item by item. */
  THIRD_PARTY_MATERIAL: 'third-party-material',
});

/** The three-way licence decision the strategy asks for. `unknown` is honest and is not a pass. */
export const LICENSE_DECISION = Object.freeze({
  ALLOWED: 'allowed',
  RESTRICTED: 'restricted',
  UNKNOWN: 'unknown',
});

/** A QA gate's state. `not-required` must say why in `note`. */
export const QA_STATUS = Object.freeze({
  PASSED: 'passed',
  PENDING: 'pending',
  FAILED: 'failed',
  NOT_REQUIRED: 'not-required',
});

/** Where an asset stands. Only `released` assets may be referenced by a public scene. */
export const RELEASE_STATUS = Object.freeze({
  /** Recorded, not yet through the pipeline. */
  CANDIDATE: 'candidate',
  /** Used by a Lab scene or a development harness only. */
  LAB: 'lab',
  RELEASED: 'released',
  RETIRED: 'retired',
});

const values = (enumeration) => Object.freeze(Object.values(enumeration));
export const ASSET_SOURCE_TYPE_IDS = values(ASSET_SOURCE_TYPE);
export const LICENSE_DECISION_IDS = values(LICENSE_DECISION);
export const QA_STATUS_IDS = values(QA_STATUS);
export const RELEASE_STATUS_IDS = values(RELEASE_STATUS);

/**
 * @typedef {object} AssetFile
 * @property {string} path repository-relative, or a URL for an upstream file that is not vendored
 * @property {string | null} sha256 hex. `null` only with a `note` saying why it could not be recorded
 * @property {number} [bytes]
 * @property {string} [note]
 */

/**
 * @typedef {object} AssetManifestEntry
 * @property {string} assetId stable, kebab-case; model profiles reference it
 * @property {number} schemaVersion
 * @property {string} sourceType one of ASSET_SOURCE_TYPE
 * @property {string} format e.g. `glb`
 * @property {string} organ taxonomy organ id
 * @property {string} structureScope what anatomy the asset covers, in words
 * @property {{ name: string, url: string, version: string, retrievedAt: string, note?: string }} source
 * @property {{ spdx: string, url: string, attribution: string, redistribution: string, commercialUse: string,
 *   decisionRecord: string | null, decisionNote: string }} license
 * @property {AssetFile[]} sources every upstream file, individually
 * @property {AssetFile} output the file the app loads
 * @property {{ coordinateSystem: string, units: string, extent: string, scaleNote: string }} geometry
 * @property {{ tools: string[], generator: string | null, steps: string[] }} pipeline
 * @property {{ partIdSource: string, mappingModule: string | null, partCount: number | null }} semanticParts
 * @property {string[]} acceptedSimplifications
 * @property {string[]} knownDefects
 * @property {{ triangles: number | null, materials: number | null, textures: number | null,
 *   bytes: number | null, targetDevices: string }} budget
 * @property {Record<string, { status: string, reference: string | null, note?: string }>} qa
 *   keys: `validator`, `anatomyTests`, `visualReview`, `clinicianReview`
 * @property {{ replaces: string | null, rollback: string }} replacement
 * @property {{ status: string, note: string }} release
 * @property {object} [atlas] required for reference-atlas
 * @property {object} [imaging] required for imaging-derived
 * @property {object} [procedural] required for procedural
 * @property {object} [molecular] required for molecular
 * @property {object} [material] required for third-party-material
 */

